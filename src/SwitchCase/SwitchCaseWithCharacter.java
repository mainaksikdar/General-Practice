package SwitchCase;

public class SwitchCaseWithCharacter {

    public static void main(String[] args) {
    char ch ='E';
    switch(ch) {
        case 'B':
            System.out.println('B');
            break;
        case 'C':
            System.out.println('C');
            break;
        case 'A':
            System.out.println('A');
            break;
        default:
            System.out.println("Test");

    }

    }
}
