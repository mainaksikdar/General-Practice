package SwitchCase;

public class SwitchCaseWithNumber {
    public static void main(String[] args) {
        int N=10;
        switch(N) {
            case 11:
                System.out.println("11");
                break;

            case 12:
                System.out.println("12");
                break;

            case 10:
                System.out.println("10");
                break;
            default:
                System.out.println("Other");
        }
    }
}
